"""Plain-text methods-and-results report for a fitted two-factor response-surface model."""
import numpy as np
import rsm


def _p(p):
    return "<0.0001" if p < 1e-4 else f"{p:.4f}"


def build_markdown(M, CA, CB, names, y_name="Response", n_runs=None, optimum=None):
    """Return a Markdown report. `optimum` is (coded point, predicted value) or None."""
    a, b = names
    L = []
    L.append(f"# Response-surface analysis: {y_name}\n")
    L.append(f"Quadratic model fitted by ordinary least squares to {M['n']} runs in two factors "
             f"(**{a}**, **{b}**), coded as x = (natural - centre) / step: "
             f"{a} centre {CA.centre:.4g}, step {CA.step:.4g}; {b} centre {CB.centre:.4g}, step {CB.step:.4g}.\n")
    L.append("## Fit quality\n")
    L.append(f"R² = {M['r2']:.4f}; adjusted R² = {M['adj_r2']:.4f}; predicted R² = {M['pred_r2']:.4f}; "
             f"CV = {M['cv']:.2f}%; adequate precision = {M['adeq_prec']:.1f}; error df = {M['dfe']}.")
    if M["adj_r2"] - M["pred_r2"] > 0.2:
        L.append("\n**Warning:** predicted R² is more than 0.2 below adjusted R²; the model may be over-fitted or an influential run drives the fit.")
    L.append("\n## ANOVA\n")
    L.append("| Source | SS | df | MS | F | p |\n|---|---:|---:|---:|---:|---:|")
    for s, ss, df, ms, f, p in M["anova"]:
        L.append(f"| {s} | {ss:.4f} | {df} | {ms:.4f} | {'' if np.isnan(f) else f'{f:.2f}'} | {'' if np.isnan(p) else _p(p)} |")
    lo = M["lof"]
    if lo and lo["ss_pe"] > 0:
        L.append(f"\nLack of fit: F = {lo['F']:.2f} on ({lo['df']}, {lo['df_pe']}) df, p = {_p(lo['p'])}.")
    elif lo:
        L.append("\nLack of fit is undefined: replicated runs are identical, so pure error is zero.")
    L.append("\n## Coefficients (coded units)\n")
    L.append("| Term | Estimate | SE | t | p |\n|---|---:|---:|---:|---:|")
    for n_, bb, s, t, p in zip(M["names"], M["beta"], M["se"], M["t"], M["p"]):
        L.append(f"| {n_} | {bb:+.4f} | {s:.4f} | {t:.2f} | {_p(p)} |")
    c = rsm.canonical(M) if {"A2", "B2", "AB"} <= set(M["terms"]) else None
    if c:
        inside = np.abs(c["xs"]).max() <= 1.4143
        L.append("\n## Canonical analysis\n")
        L.append(f"Stationary point at {a} = {CA.to_natural(c['xs'][0]):.3f}, {b} = {CB.to_natural(c['xs'][1]):.3f} "
                 f"(predicted {c['ys']:.3f}); eigenvalues {c['eig'][0]:.3f} and {c['eig'][1]:.3f}: a **{c['kind']}**"
                 + ("" if inside else ", outside the design region (extrapolation)") + ".")
    if optimum is not None:
        pt, yo = optimum
        L.append("\n## Best setting inside the design region\n")
        L.append(f"{a} = {CA.to_natural(pt[0]):.3f}, {b} = {CB.to_natural(pt[1]):.3f}: predicted {yo:.3f}. "
                 "Confirm with replicate runs before relying on it.")
    L.append("\n---\nGenerated by the RSM analyser. Predictions outside the design region are extrapolation.")
    return "\n".join(L) + "\n"
